"""Карманный переводчик под уровень ученика (/tcz, /teng).

Двунаправленный: не-целевой язык → целевой (жёстко в рамках уровня ученика,
чтобы перевод можно было запомнить и произнести самому), целевой → русский
(без ограничений — родной). Направление определяет модель в том же вызове.
"""
from core.ai import _complete

_TARGETS = {
    "cz": {"lang": "чешский", "level": "строго A2"},
    "eng": {"lang": "английский", "level": "A2–B1"},
}


def translate(text: str, target: str) -> str:
    """Один LLM-вызов: перевод в рамках уровня либо обратно на русский."""
    cfg = _TARGETS[target]
    lang, level = cfg["lang"], cfg["level"]
    system = f"""Ты переводчик-помощник ученика, изучающего {lang} (уровень {level}).

Определи язык присланного текста:
- Если текст НЕ на {lang} языке — переведи его на {lang}. ЖЁСТКОЕ ограничение:
  только лексика и грамматика уровня {level}. Не выбирай самый естественный или
  элегантный перевод — выбирай тот, который ученик этого уровня сможет сам
  запомнить и произнести. Если мысль невозможно выразить средствами уровня —
  переведи упрощённо и одной строкой пометь: «⚠️ упрощено: …» с пояснением,
  что именно упрощено.
- Если текст УЖЕ на {lang} языке — переведи его на русский (обычный естественный
  русский, без ограничений уровня).

Формат ответа: первой строкой — только перевод. Затем, ТОЛЬКО если есть что-то
неочевидное и полезное (возвратная частица, нестандартный предлог, ложный друг
переводчика, устойчивое выражение) — максимум 1–2 короткие строки заметок,
каждая начинается с 💡. Если ничего неочевидного нет — только перевод.
Никаких приветствий, преамбул и предложений помочь ещё."""
    return _complete(system, text, max_tokens=600)
